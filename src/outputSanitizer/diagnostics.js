function diagnosticCollectTargets(root) {
    if (!root?.querySelectorAll)
        return [];
    const semanticSelectors = [
        '.hidden-thought',
        '[class*="hidden"]',
        '[class*="reveal"]',
        '[class*="secret"]',
        `[${RENDERED_BUTTON_ADJACENT_HIDDEN_ITEM_ATTR}]`,
        `[${RENDERED_CSS_STATE_SIBLING_ITEM_ATTR}]`,
    ];
    const seen = new Set();
    const result = [];
    const append = element => {
        if (!element || seen.has(element))
            return false;
        if (element.closest?.(`[${INTERACTION_DIAGNOSTIC_PANEL_ATTR}]`))
            return false;
        if (element.closest?.(`[${SOURCE_TRUNCATION_NOTICE_ATTR}]`))
            return false;
        const tagName = String(element.tagName || '').toLowerCase();
        if (/^(?:input|select|textarea|option|button|label|style|script|template)$/.test(tagName))
            return false;
        seen.add(element);
        result.push(element);
        return result.length >= 12;
    };
    for (const element of root.querySelectorAll(semanticSelectors.join(','))) {
        if (append(element))
            return result;
    }
    for (const element of root.querySelectorAll('[style]')) {
        if (!getRenderedStyleSnapshot(element).hidden)
            continue;
        if (append(element))
            return result;
    }
    for (const button of root.querySelectorAll('button')) {
        const target = findRenderedButtonAdjacentHiddenTarget(button);
        if (append(target))
            break;
    }
    return result;
}
