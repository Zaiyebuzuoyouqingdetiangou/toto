function getDiagnosticRootFromTarget(target) {
    if (!target?.closest)
        return null;
    if (target.closest(`[${INTERACTION_DIAGNOSTIC_PANEL_ATTR}]`))
        return null;
    const toto = target.closest(MIRROR_TOTO_SELECTOR);
    if (toto && isInsideChatMessage(toto))
        return toto;
    const details = target.closest('details');
    if (details && isRabbitMirrorDetails(details) && isInsideChatMessage(details))
        return details;
    const body = target.closest('.mes_text');
    if (body && isInsideChatMessage(body))
        return body;
    const message = target.closest('.mes, [mesid], [data-message-id], [data-messageid]');
    const messageBody = message?.querySelector?.('.mes_text');
    if (messageBody && isInsideChatMessage(messageBody))
        return messageBody;
    return null;
}
